# Program 1: Built-in Polymorphism
string_data = "Keshav"
list_data = [10, 20, 30, 40]
dict_data = {"name": "Keshav", "language": "Python"}

# The len() function works on strings, lists, and dictionaries seamlessly
print(f"String length: {len(string_data)}")  # Counts characters
print(f"List length: {len(list_data)}")      # Counts elements
print(f"Dict length: {len(dict_data)}")      # Counts key-value pairs